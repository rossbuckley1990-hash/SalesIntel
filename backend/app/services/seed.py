def seed_sample_data(db: Session) -> dict[str, int]:
    opportunities = [Opportunity(**payload) for payload in OPPORTUNITIES]
    db.add_all(opportunities)
    db.flush()

    market_signals = []
    for index, (
        title,
        buyer_name,
        sector,
        region,
        estimated_value,
        expected_tender_date,
        suggested_action,
    ) in enumerate(MARKET_SIGNALS):
        signal = MarketSignal(
            title=title,
            buyer_name=buyer_name,
            sector=sector,
            region=region,
            estimated_value=estimated_value,
            expected_tender_date=date.fromisoformat(expected_tender_date),
            source_type="synthetic_market_signal",
            source_url=f"https://example.invalid/market-signals/{index + 1}",
            confidence_score=round(0.62 + (index % 6) * 0.05, 2),
            suggested_action=suggested_action,
        )
        market_signals.append(enrich_market_signal(signal))

    buyer_profiles = [
        BuyerProfile(
            buyer_name=buyer_name,
            sector=sector,
            region=region,
            estate_size=estate_size,
            procurement_drivers=procurement_drivers,
            pain_points=pain_points,
            decision_criteria=decision_criteria,
            relationship_status=relationship_status,
            next_best_action=next_best_action,
        )
        for (
            buyer_name,
            sector,
            region,
            estate_size,
            procurement_drivers,
            pain_points,
            decision_criteria,
            relationship_status,
            next_best_action,
        ) in BUYER_PROFILES
    ]

    competitor_profiles = [
        CompetitorProfile(
            name=name,
            sectors=sectors,
            strengths=strengths,
            weaknesses=weaknesses,
            pricing_behaviour=pricing_behaviour,
            threat_level=threat_level,
            counter_strategy=counter_strategy,
        )
        for (
            name,
            sectors,
            strengths,
            weaknesses,
            pricing_behaviour,
            threat_level,
            counter_strategy,
        ) in COMPETITOR_PROFILES
    ]

    executive_actions = [
        ExecutiveAction(
            priority=priority,
            category=category,
            owner=owner,
            due_date=date.fromisoformat(due_date),
            related_opportunity_id=opportunities[opportunity_index].id,
            commercial_value=opportunities[opportunity_index].estimated_total_contract_value,
            reason=reason,
            recommended_action=recommended_action,
            status=status,
        )
        for (
            priority,
            category,
            owner,
            due_date,
            opportunity_index,
            reason,
            recommended_action,
            status,
        ) in EXECUTIVE_ACTIONS
    ]

    finance_forecasts = [
        FinanceForecast(
            opportunity_id=opportunities[opportunity_index].id,
            forecast_category=forecast_category,
            start_month=start_month,
            revenue_to_year_end=revenue_to_year_end,
            estimated_margin=estimated_margin,
            margin_percentage=margin_percentage,
            probability_weighting=probability_weighting,
            risk_adjustment=risk_adjustment,
            notes=notes,
        )
        for (
            start_month,
            revenue_to_year_end,
            estimated_margin,
            margin_percentage,
            probability_weighting,
            risk_adjustment,
            opportunity_index,
            notes,
        ) in FORECAST_MONTHS
        for forecast_category in ["commit"]
    ]

    db.add_all(
        [
            *market_signals,
            *buyer_profiles,
            *competitor_profiles,
            *executive_actions,
            *finance_forecasts,
        ]
    )
    db.commit()

    return {
        "opportunities": len(opportunities),
        "market_signals": len(market_signals),
        "buyer_profiles": len(buyer_profiles),
        "competitor_profiles": len(competitor_profiles),
        "executive_actions": len(executive_actions),
        "finance_forecasts": len(finance_forecasts),
    }
